/**
 * State Schema Definition for CyberSahayak LangGraph.js Workflow
 *
 * Implements a structured, typed graph state with message reducers
 * to support multi-turn conversation memory, intent categorization,
 * conditional RAG retrieval, and response validation.
 */

const { Annotation } = require('@langchain/langgraph');

const CyberSahayakState = Annotation.Root({
  // The current active user message
  userMessage: Annotation({
    reducer: (prev, next) => next || prev,
    default: () => '',
  }),

  // Chronological LangChain BaseMessages (HumanMessage, AIMessage, SystemMessage)
  messages: Annotation({
    reducer: (prev, next) => (Array.isArray(next) ? prev.concat(next) : prev.concat([next])),
    default: () => [],
  }),

  // Unique conversation identifier to isolate separate chats
  conversationId: Annotation({
    reducer: (prev, next) => next || prev || 'default-session',
    default: () => 'default-session',
  }),

  // Intent classification & routing decision
  intent: Annotation({
    reducer: (prev, next) => (next ? { ...prev, ...next } : prev),
    default: () => ({
      category: 'general_cyber',
      urgency: 'low',
      needsRetrieval: false,
      confidence: 1.0,
      rationale: '',
    }),
  }),

  // Optimized query for knowledge base retrieval (if applicable)
  retrievalQuery: Annotation({
    reducer: (prev, next) => next || prev || '',
    default: () => '',
  }),

  // Semantically retrieved documents from cyber-law.pdf
  retrievedDocs: Annotation({
    reducer: (prev, next) => (next !== undefined ? next : prev),
    default: () => [],
  }),

  // Initial draft response generated by the LLM
  draftResponse: Annotation({
    reducer: (prev, next) => next || prev || '',
    default: () => '',
  }),

  // Safety, guardrail, and quality validation results
  validation: Annotation({
    reducer: (prev, next) => (next ? { ...prev, ...next } : prev),
    default: () => ({
      isValid: true,
      hasFIRViolation: false,
      hasCredentialViolation: false,
      hasHelplineMention: true,
      clarificationCount: 0,
      extractedQuestion: null,
      sanitized: false,
      issues: [],
    }),
  }),

  // The verified, finalized response returned to the user
  finalResponse: Annotation({
    reducer: (prev, next) => next || prev || '',
    default: () => '',
  }),

  // Tracking previously asked questions to avoid repeatedly asking the same thing
  clarificationsAsked: Annotation({
    reducer: (prev, next) => {
      const existing = new Set(prev || []);
      if (Array.isArray(next)) {
        next.forEach((item) => existing.add(item));
      } else if (next) {
        existing.add(next);
      }
      return Array.from(existing);
    },
    default: () => [],
  }),

  // Execution tracking metadata (nodes visited, model used, latency, etc.)
  metadata: Annotation({
    reducer: (prev, next) => (next ? { ...prev, ...next } : prev),
    default: () => ({
      provider: 'unknown',
      model: 'unknown',
      isDemo: false,
      executionNodes: [],
      timestamp: new Date().toISOString(),
    }),
  }),
});

module.exports = {
  CyberSahayakState,
};
